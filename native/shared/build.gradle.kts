import java.util.Base64
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

// The platform-neutral core: models, the capabilities and talk bundle clients, the SQLite store and
// keyword search, and the interfaces that each platform implements (embeddings, Bluetooth,
// notifications, secure storage). No UI lives here.
plugins {
    alias(libs.plugins.kotlinMultiplatform)
    alias(libs.plugins.androidMultiplatformLibrary)
    alias(libs.plugins.kotlinxSerialization)
}

/**
 * Turns the contract fixtures (docs/contracts) into a Kotlin source file for commonTest, so the same
 * bytes reach the tests on the JVM and on the iOS simulator without any file access at test time.
 * Each file is stored as base64 in chunks, because a JVM class file limits one string constant to
 * 65,535 bytes.
 */
abstract class GenerateContractFixtures : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val fixturesDir: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = fixturesDir.get().asFile
        val files = listOf("capabilities", "bundle", "people-api")
            .flatMap { sub -> root.resolve(sub).walkTopDown().filter { it.isFile }.toList() }
            .sortedBy { it.relativeTo(root).invariantSeparatorsPath }
        val out = StringBuilder()
        out.append("// Generated by the generateContractFixtures task from contracts/fixtures. Do not edit.\n")
        out.append("package app.conferencecaddie.shared.fixtures\n\n")
        out.append("internal object ContractFixtureData {\n")
        out.append("    val files: Map<String, List<String>> = mapOf(\n")
        for (file in files) {
            val name = file.relativeTo(root).invariantSeparatorsPath
            val encoded = Base64.getEncoder().encodeToString(file.readBytes())
            out.append("        \"").append(name).append("\" to listOf(\n")
            encoded.chunked(30_000).forEach { out.append("            \"").append(it).append("\",\n") }
            out.append("        ),\n")
        }
        out.append("    )\n}\n")
        val target = outputDir.get().asFile.resolve("app/conferencecaddie/shared/fixtures/ContractFixtureData.kt")
        target.parentFile.mkdirs()
        target.writeText(out.toString())
    }
}

val generateContractFixtures = tasks.register<GenerateContractFixtures>("generateContractFixtures") {
    fixturesDir.set(rootProject.layout.projectDirectory.dir("../contracts/fixtures"))
    outputDir.set(layout.buildDirectory.dir("generated/contractFixtures/kotlin"))
}

kotlin {
    android {
        namespace = "app.conferencecaddie.shared"
        compileSdk = libs.versions.android.compileSdk.get().toInt()
        minSdk = libs.versions.android.minSdk.get().toInt()

        compilerOptions {
            jvmTarget = JvmTarget.JVM_17
        }
    }

    // The JVM target exists for the tests: commonTest runs there on Linux CI and on a Mac, with the
    // desktop build of the bundled SQLite driver. Android host tests cannot load that driver's
    // native library, which is why they are not used.
    jvm {
        compilerOptions {
            jvmTarget = JvmTarget.JVM_17
        }
    }

    // iosX64 is left out: Compose Multiplatform 1.12 publishes no x86_64 simulator artifacts, and
    // Xcode 27 runs only on Apple silicon.
    iosArm64()
    iosSimulatorArm64()

    sourceSets {
        commonMain.dependencies {
            api(libs.kotlinx.coroutines.core)
            api(libs.kotlinx.serialization.json)
            api(libs.kotlinx.datetime)
            // BundleFiles takes a kotlinx-io Path, so the platforms and tests that build one see it.
            api(libs.kotlinx.io.core)
            implementation(libs.ktor.client.core)
            implementation(libs.androidx.sqlite.bundled)
        }
        androidMain.dependencies {
            implementation(libs.ktor.client.okhttp)
        }
        jvmMain.dependencies {
            implementation(libs.ktor.client.okhttp)
        }
        iosMain.dependencies {
            implementation(libs.ktor.client.darwin)
        }
        commonTest {
            kotlin.srcDir(generateContractFixtures.flatMap { it.outputDir })
            dependencies {
                implementation(libs.kotlin.test)
                implementation(libs.kotlinx.coroutines.test)
                implementation(libs.ktor.client.mock)
            }
        }
    }
}

// The live People API harness (jvmTest, LivePeopleSmokeTest) runs only when a backend is named:
//   ./gradlew :shared:jvmTest --tests '*LivePeopleSmokeTest*' -Pcaddie.liveBase=https://...
// It then always runs (never up to date, never from the build cache) and prints its PASS, FAIL and
// SKIP lines. Without the property the test returns at once.
val liveBase: String = providers.gradleProperty("caddie.liveBase").orElse("").get()
tasks.named<Test>("jvmTest") {
    inputs.property("caddieLiveBase", liveBase)
    systemProperty("caddie.liveBase", liveBase)
    if (liveBase.isNotEmpty()) {
        outputs.upToDateWhen { false }
        outputs.cacheIf { false }
        testLogging {
            showStandardStreams = true
        }
    }
}
