kotlin {
    android {
        namespace = "app.conferencecaddie.shared"
        compileSdk = libs.versions.android.compileSdk.get().toInt()
        minSdk = libs.versions.android.minSdk.get().toInt()

        compilerOptions {
            jvmTarget = JvmTarget.JVM_17
        }
    }

    // The JVM target exists for the tests: commonTest runs there on Linux CI and on a Mac, with the
    // desktop build of the bundled SQLite driver. Android host tests cannot load that driver's
    // native library, which is why they are not used.
    jvm {
        compilerOptions {
            jvmTarget = JvmTarget.JVM_17
        }
    }

    // iosX64 is left out: Compose Multiplatform 1.12 publishes no x86_64 simulator artifacts, and
    // Xcode 27 runs only on Apple silicon.
    //
    // ONNX Runtime's C API through cinterop, linked statically: the static library goes into the
    // klib, and from there into the ComposeApp framework and the test executables.
    // src/nativeInterop/cinterop/onnxruntime.def lists the system frameworks it needs.
    fun KotlinNativeTarget.onnxRuntime(slice: String) {
        compilations.getByName("main").cinterops.create("onnxruntime") {
            definitionFile.set(project.file("src/nativeInterop/cinterop/onnxruntime.def"))
            includeDirs(onnxRuntimeAppleDir.map { it.dir("Headers") })
            extraOpts("-libraryPath", onnxRuntimeAppleDir.get().dir(slice).asFile.absolutePath, "-staticLibrary", "libonnxruntime.a")
        }
    }
    // Partial linkage: by default Kotlin/Native links a binary even when a klib calls a function or a
    // class that the dependency version on the classpath no longer has. The link succeeds, and the call
    // throws IrLinkageError only when it runs. At ERROR the link fails instead, so a dependency update
    // that drops something another library calls stops the build, not the app (DECISIONS.md, "Native
    // build hardening"). Partial linkage runs when a binary is linked (here the test executables), so
    // the option goes to the link tasks. A debug link reuses Kotlin/Native's cache of each library,
    // whose key does not include this level; native.yml's ~/.konan cache key names it, so CI rebuilds
    // those caches at ERROR. Only a link without caches (the release framework) names the symbol.
    targets.withType<KotlinNativeTarget>().configureEach {
        binaries.configureEach {
            linkTaskProvider.configure { toolOptions.freeCompilerArgs.add("-Xpartial-linkage-loglevel=ERROR") }
        }
    }
    iosArm64 { onnxRuntime("ios-arm64") }
    iosSimulatorArm64 {
        onnxRuntime("ios-simulator-arm64")
        // The Keychain tests (IosSecureStoreTest) need an app's entitlements. The simulator reads them
        // from the executable's __TEXT,__entitlements section, which is where Xcode puts them for a
        // simulator build, so the test executable gets one too; no signing identity is involved.
        binaries.withType<TestExecutable>().configureEach {
            linkerOpts("-sectcreate", "__TEXT", "__entitlements", simulatorTestEntitlements.asFile.absolutePath)
            linkTaskProvider.configure { inputs.file(simulatorTestEntitlements) }
        }
    }

    sourceSets {
        commonMain.dependencies {
            api(libs.kotlinx.coroutines.core)
            api(libs.kotlinx.serialization.json)
            api(libs.kotlinx.datetime)
            // BundleFiles takes a kotlinx-io Path, so the platforms and tests that build one see it.
            api(libs.kotlinx.io.core)
            implementation(libs.ktor.client.core)
            implementation(libs.androidx.sqlite.bundled)
        }
        // ONNX Runtime's Java API is the same on Android and the JVM, so one source file
        // (src/ortJava) serves both, compiled against each platform's own artifact.
        androidMain {
            kotlin.srcDir("src/ortJava/kotlin")
            dependencies {
                implementation(libs.ktor.client.okhttp)
                implementation(libs.onnxruntime.android)
            }
        }
        jvmMain {
            kotlin.srcDir("src/ortJava/kotlin")
            dependencies {
                implementation(libs.ktor.client.okhttp)
                implementation(libs.onnxruntime.jvm)
            }
        }
        iosMain.dependencies {
            implementation(libs.ktor.client.darwin)
        }
        commonTest {
            kotlin.srcDir(generateContractFixtures.flatMap { it.outputDir })
            dependencies {
                implementation(libs.kotlin.test)
                implementation(libs.kotlinx.coroutines.test)
                implementation(libs.ktor.client.mock)
            }
        }
    }
}

