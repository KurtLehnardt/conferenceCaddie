package app.conferencecaddie.shared.importer

import kotlin.test.Test
import kotlin.test.assertTrue
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long

/**
 * The device's import against the Worker's on the cases of [ImportParityFixtures] (generated by
 * native/shared/scripts/generate-import-fixtures.mjs from worker/src/talks/import-parse.js and
 * import.js): the same format, the same entries, the same candidates with the same speaker text and
 * time hints, and the same matches with the same confidence labels, in the same order. Every
 * difference of every case is reported together.
 */
class ImportParityTest {
    private val talks = ImportParityFixtures.talks.map { ImportFixtures.talk(ImportParityFixtures.EVENT, it.n, it.title, it.speakers, it.start, it.kind) }
    private val matcher = ScheduleMatcher(talks)

    private fun JsonObject.str(key: String): String? = (this[key] as? JsonPrimitive)?.takeIf { it.isString }?.content

    @Test
    fun theDeviceReadsEveryCaseAsTheWorkerDoes() {
        val problems = ArrayList<String>()
        for (case in ImportParityFixtures.cases) {
            val expected = Json.parseToJsonElement(case.expected).jsonObject
            val conference = ImportConference(ImportParityFixtures.EVENT, case.startDate, case.zone)
            val prepared = ScheduleImport.Prepared(case.text.removePrefix("﻿"), case.filename, case.mime, isFile = false)
            val detected = ScheduleParser.detect(prepared.text, prepared.filename, prepared.mime)
            val format = detected.format.name.lowercase()
            if (format != expected.str("format")) problems += "${case.name}: format $format, expected ${expected.str("format")}"
            val entries = ScheduleParser.entries(prepared.text, detected, prepared.filename, conference)
            val entryCount = expected["entries"]!!.jsonPrimitive.int
            if (entries.size != entryCount) problems += "${case.name}: ${entries.size} entries, expected $entryCount"

            val candidates = ScheduleImport.candidatesOf(prepared, conference)
            val want = expected["candidates"]!!.jsonArray.map { it.jsonObject }
            val got = candidates.map { c -> listOf(c.text, c.entries.toList(), c.exact, c.context, c.hintMs) }
            val wanted = want.map { c ->
                listOf(
                    c.str("text"),
                    c["entries"]!!.jsonArray.map { it.jsonPrimitive.int },
                    c["exact"]!!.jsonPrimitive.boolean,
                    c.str("context"),
                    (c["hint"] as? JsonPrimitive)?.takeIf { it !is JsonNull }?.long,
                )
            }
            if (got != wanted) {
                val i = (0 until maxOf(got.size, wanted.size)).first { got.getOrNull(it) != wanted.getOrNull(it) }
                problems += "${case.name}: candidate $i is ${got.getOrNull(i)}, expected ${wanted.getOrNull(i)} (${got.size} of ${wanted.size})"
            }

            val result = matcher.run(candidates, prepared.text.length)
            val matched = result.matched.map { listOf(it.talk.talkId, it.confidence.wire, it.excerpt) }
            val wantMatched = (expected["matched"] as JsonArray).map { m -> m.jsonObject.let { listOf(it.str("talk_id"), it.str("confidence"), it.str("excerpt")) } }
            if (matched != wantMatched) problems += "${case.name}: matched $matched, expected $wantMatched"
            val unmatched = expected["unmatched_count"]!!.jsonPrimitive.int
            if (result.unmatchedCount != unmatched) problems += "${case.name}: ${result.unmatchedCount} unmatched, expected $unmatched"
            val chars = expected["extracted_chars"]!!.jsonPrimitive.int
            if (result.extractedChars != chars) problems += "${case.name}: ${result.extractedChars} characters, expected $chars"
        }
        assertTrue(problems.isEmpty(), "${problems.size} differences:\n" + problems.joinToString("\n"))
    }
}
