package app.conferencecaddie.shared.embed

import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNotEquals
import kotlin.test.assertTrue
import kotlin.time.TimeSource

// The real vocabulary, read once for all tests.
private val vocabLines: List<String> by lazy { embeddingText("vocab.txt").split('\n').map { it.removeSuffix("\r") } }
private val bge: WordPieceTokenizer by lazy { WordPieceTokenizer.fromVocab(embeddingText("vocab.txt")) }

// The tokenizer against the ids transformers.js gives (TokenizerFixtures, generated by
// native/shared/scripts/generate-tokenizer-fixtures.mjs), plus small cases checked by hand.
class WordPieceTokenizerTest {
    private fun id(token: String): Int = vocabLines.indexOf(token).also { check(it >= 0) { "$token is not in vocab.txt" } }

    private fun ids(case: TokenizerFixtures.Case): IntArray =
        case.ids.split(',').map { it.toInt() }.toIntArray()

    private fun tokens(ids: IntArray): String = ids.joinToString(" ") { vocabLines[it] }

    @Test
    fun everyFixtureCaseGivesTheIdsOfTransformersJs() {
        val failures = TokenizerFixtures.cases.mapNotNull { case ->
            val expected = ids(case)
            val actual = bge.encode(case.text)
            if (expected.contentEquals(actual)) {
                null
            } else {
                "${case.name}:\n  expected ${tokens(expected)}\n  actual   ${tokens(actual)}"
            }
        }
        assertTrue(failures.isEmpty(), "${failures.size} of ${TokenizerFixtures.cases.size} cases differ:\n" + failures.joinToString("\n"))
        assertTrue(TokenizerFixtures.cases.size >= 150, "the fixture has ${TokenizerFixtures.cases.size} cases")
    }

    @Test
    fun tokenizeGivesThePiecesBetweenClsAndSep() {
        for (case in TokenizerFixtures.cases.filter { it.untruncated <= 512 }) {
            val expected = ids(case)
            val pieces = bge.tokenize(case.text)
            assertEquals(expected.size - 2, pieces.size, case.name)
            assertEquals(expected.drop(1).dropLast(1).map { vocabLines[it] }, pieces, case.name)
        }
    }

    @Test
    fun aLongTextIsCutAfterMaxTokensIdsWithoutSep() {
        val long = TokenizerFixtures.cases.filter { it.untruncated > 512 }
        assertTrue(long.size >= 2, "the fixture has ${long.size} cases above 512 ids")
        for (case in long) {
            val actual = bge.encode(case.text)
            assertEquals(512, actual.size, case.name)
            assertEquals(id("[CLS]"), actual.first(), case.name)
            assertNotEquals(id("[SEP]"), actual.last(), "transformers.js cuts [SEP] off too: ${case.name}")
            assertEquals(case.untruncated - 2, bge.tokenize(case.text).size, case.name)
        }
        // The cut is a prefix of the whole sequence for any limit.
        val case = long.first()
        val all = ids(case)
        for (limit in listOf(1, 2, 3, 17, 100, 511)) {
            assertContentEquals(all.copyOf(limit), bge.encode(case.text, limit), "limit $limit")
        }
        val exact = TokenizerFixtures.cases.single { it.name == "exactly 512 ids" }
        assertEquals(512, exact.untruncated)
        assertEquals(id("[SEP]"), bge.encode(exact.text).last())
        assertContentEquals(ids(exact).copyOf(511), bge.encode(exact.text, 511))
    }

    @Test
    fun helloWorldByHand() {
        val expected = listOf("[CLS]", "hello", ",", "world", "!", "[SEP]").map { id(it) }
        assertEquals(listOf(101, 7592, 1010, 2088, 999, 102), expected)
        assertContentEquals(expected.toIntArray(), bge.encode("Hello, world!"))
        assertContentEquals(expected.take(3).toIntArray(), bge.encode("Hello, world!", maxTokens = 3))
        assertEquals(listOf("hello", ",", "world", "!"), bge.tokenize("  HELLO ,world!  "))
        assertContentEquals(intArrayOf(id("[CLS]"), id("[SEP]")), bge.encode(""))
        assertContentEquals(intArrayOf(id("[CLS]"), id("[SEP]")), bge.encode(" \t\n\u00A0\u200B"))
    }

    @Test
    fun smallVocabularyByHand() {
        val t = WordPieceTokenizer.fromVocab("[PAD]\r\n[UNK]\r\n[CLS]\r\n[SEP]\r\nun\r\n##aff\r\n##able\r\ncafe\r\n中\r\n.\r\n")
        assertEquals(listOf("un", "##aff", "##able"), t.tokenize("unaffable"))
        assertContentEquals(intArrayOf(2, 4, 5, 6, 3), t.encode("unaffable"))
        // A word that cannot be cut completely is one [UNK], not a partial match.
        assertEquals(listOf("[UNK]", "."), t.tokenize("unaffablex."))
        assertEquals(listOf("cafe", "中", "[UNK]", "[SEP]", "cafe"), t.tokenize("CAFÉ中文[SEP]Café"))
        assertEquals(listOf("[UNK]"), t.tokenize("un" + "aff".repeat(33)), "101 characters")
        assertEquals(listOf("un") + List(31) { "##aff" } + "##able", t.tokenize("un" + "aff".repeat(31) + "able"), "99 characters")
    }

    @Test
    fun fromVocabRejectsAVocabularyWithoutSpecialTokens() {
        val all = listOf("[PAD]", "[UNK]", "[CLS]", "[SEP]", "hello")
        for (missing in listOf("[PAD]", "[UNK]", "[CLS]", "[SEP]")) {
            val e = assertFailsWith<IllegalArgumentException> { WordPieceTokenizer.fromVocab((all - missing).joinToString("\n")) }
            assertTrue(missing in e.message.orEmpty(), e.message)
        }
        assertFailsWith<IllegalArgumentException> { WordPieceTokenizer.fromVocab("") }
        assertContentEquals(intArrayOf(2, 4, 3), WordPieceTokenizer.fromVocab(all.joinToString("\n")).encode("hello"))
    }

    @Test
    fun encodingAnAbstractIsFast() {
        val abstract = TokenizerFixtures.cases.filter { it.name.startsWith("longest talk") }.maxBy { it.text.length }.text
        repeat(20) { bge.encode(abstract) }
        val runs = 200
        val start = TimeSource.Monotonic.markNow()
        repeat(runs) { bge.encode(abstract) }
        val perText = start.elapsedNow() / runs
        println("WordPieceTokenizer: ${abstract.length} characters in $perText")
        // Generous, so that only a pathological slowdown fails; the JVM takes well under a millisecond.
        assertTrue(perText.inWholeMilliseconds < 50, "encoding ${abstract.length} characters took $perText")
    }
}
