/**
 * Turns shared/fixtures/query-embeddings.v1.json (the fp32 reference vectors of the 72 test queries)
 * into a Kotlin source for the Android device tests, which measure the shipped model on an emulator
 * or phone. The JSON is kept as base64 chunks, as shared's contract fixtures are.
 */
abstract class GenerateQueryFixture : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val fixture: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val encoded = Base64.getEncoder().encodeToString(fixture.get().asFile.readBytes())
        val out = StringBuilder()
        out.append("// Generated by the generateQueryFixture task from shared/fixtures/query-embeddings.v1.json. Do not edit.\n")
        out.append("package app.conferencecaddie.ui\n\n")
        out.append("internal object QueryFixtureData {\n    val chunks: List<String> = listOf(\n")
        encoded.chunked(30_000).forEach { out.append("        \"").append(it).append("\",\n") }
        out.append("    )\n}\n")
        val target = outputDir.get().asFile.resolve("app/conferencecaddie/ui/QueryFixtureData.kt")
        target.parentFile.mkdirs()
        target.writeText(out.toString())
    }
}

val generateQueryFixture = tasks.register<GenerateQueryFixture>("generateQueryFixture") {
    fixture.set(rootProject.layout.projectDirectory.file("shared/fixtures/query-embeddings.v1.json"))
    outputDir.set(layout.buildDirectory.dir("generated/queryFixture/kotlin"))
}

