// The fork-and-operate documentation must stay true to the repository: its relative links resolve
// (files and heading anchors), it names none of the maintainer's own identifiers, every repository
// path and npm script it mentions exists, and every caddie-admin command it shows is a command of
// the tool with flags that command accepts.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { COMMAND_TREE } from '../admin/cli.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

// The documents this test owns. README.md is checked for links only, because it records the
// maintainer's own install addresses on purpose (the fork-values test allow-lists it).
const NEW_DOCS = ['docs/FORK.md', 'docs/ADMIN_CLI.md', ...fs.readdirSync(path.join(ROOT, 'docs', 'fork')).filter((f) => f.endsWith('.md')).map((f) => `docs/fork/${f}`)];
const LINKED_DOCS = [...NEW_DOCS, 'README.md', 'docs/OPERATOR_CHECKLIST.md'];

const read = (file) => fs.readFileSync(path.join(ROOT, file), 'utf8');

// Text outside fenced code blocks.
function prose(text) {
  return text.replace(/^```[\s\S]*?^```/gm, '');
}

// GitHub's heading anchor: lowercase, punctuation other than hyphens, underscores and spaces
// dropped, spaces to hyphens.
function anchors(file) {
  const out = new Set();
  for (const m of prose(read(file)).matchAll(/^#{1,6}\s+(.+?)\s*$/gm)) {
    out.add(m[1].replace(/`/g, '').toLowerCase().replace(/[^\p{L}\p{N}_\- ]/gu, '').replace(/ /g, '-'));
  }
  return out;
}

test('every relative link in the documents resolves to a file and, with a fragment, to a heading', () => {
  const problems = [];
  for (const file of LINKED_DOCS) {
    for (const m of prose(read(file)).matchAll(/\]\(([^)\s]+)\)/g)) {
      const target = m[1];
      if (/^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
      const [rel, fragment] = target.split('#');
      const resolved = rel === '' ? file : path.posix.normalize(path.posix.join(path.posix.dirname(file), rel));
      const abs = path.join(ROOT, resolved);
      if (!fs.existsSync(abs)) {
        problems.push(`${file}: ${target} does not exist`);
        continue;
      }
      if (fragment && abs.endsWith('.md') && !anchors(resolved).has(fragment)) problems.push(`${file}: ${target} has no such heading`);
    }
  }
  assert.deepEqual(problems, []);
});

test('the new documents name none of the maintainer\'s own identifiers', () => {
  const identifiers = [/fc875c88f9f44f159f1a359ee724d82b/i, /project-9205d6eb-366e-4844-b77/i, /krlehnardt/i, /kurtlehnardt/i, /conference-caddie-265846417372/i, /265846417372/];
  const problems = [];
  for (const file of NEW_DOCS) {
    const text = read(file);
    for (const re of identifiers) if (re.test(text)) problems.push(`${file}: ${re.source}`);
  }
  assert.deepEqual(problems, []);
});

test('every repository path and npm script the new documents mention exists', () => {
  const scripts = JSON.parse(read('package.json')).scripts;
  const problems = [];
  // Files the documents name that a clone does not hold: ignored or generated by the reader's own
  // setup, or optional.
  const absentOk = new Set([
    'native/iosApp/Configuration/Local.xcconfig', // git-ignored, copied from the .example file
    'web/android/app/google-services.json', // git-ignored, the reader's own Firebase file
    'web/dist', // built by npm --prefix web run build
    'data/takedowns.json', // optional: the file exists only once a takedown has been granted
  ]);
  const pathRe = /^(?:scripts|docs|worker|native|web|server|data|config|contracts|tools|test|\.github)\/[A-Za-z0-9_./-]*[A-Za-z0-9_]$/;
  for (const file of NEW_DOCS) {
    const text = read(file);
    for (const m of text.matchAll(/`([^`\n]+)`/g)) {
      const token = m[1].trim();
      if (pathRe.test(token) && !absentOk.has(token) && !fs.existsSync(path.join(ROOT, token)) && !fs.existsSync(path.join(ROOT, token.replace(/\/$/, '')))) {
        problems.push(`${file}: path ${token} does not exist`);
      }
    }
    for (const m of text.matchAll(/\bnpm run ([a-z:-]+)/g)) {
      if (!Object.hasOwn(scripts, m[1])) problems.push(`${file}: npm script ${m[1]} does not exist`);
    }
  }
  assert.deepEqual(problems, []);
});

const GLOBAL_FLAGS = ['backend', 'json', 'yes', 'confirm', 'dry-run', 'help'];

// Command lines of a document: every line of a fenced block, with backslash continuations joined,
// and every inline `code` span.
function commandLines(file) {
  const text = read(file);
  const lines = [];
  for (const block of text.matchAll(/^```[^\n]*\n([\s\S]*?)^```/gm)) {
    lines.push(...block[1].replace(/\\\n\s*/g, ' ').split('\n'));
  }
  for (const m of prose(text).matchAll(/`([^`\n]+)`/g)) lines.push(m[1]);
  return lines.map((l) => l.trim()).filter(Boolean);
}

test('ADMIN_CLI.md documents every command of the tool, and each one answers -h', () => {
  const text = read('docs/ADMIN_CLI.md');
  for (const [area, { commands }] of Object.entries(COMMAND_TREE)) {
    for (const command of Object.keys(commands)) {
      const re = new RegExp(`${area} ${command}\\b`);
      assert.ok(re.test(text), `ADMIN_CLI.md does not mention "${area} ${command}"`);
      const r = spawnSync(process.execPath, ['scripts/caddie-admin.mjs', area, command, '-h'], { cwd: ROOT, encoding: 'utf8' });
      assert.equal(r.status, 0, `${area} ${command} -h exited ${r.status}`);
      assert.match(r.stdout, /^Usage: caddie-admin /);
    }
  }
});

test('every caddie-admin example in every document names a real command and flags that command accepts', () => {
  const problems = [];
  let count = 0;
  for (const file of NEW_DOCS) {
    for (const line of commandLines(file)) {
      const m = /(?:^|\s)(?:caddie-admin|node scripts\/caddie-admin\.mjs|npm run admin --)\s+(.+)$/.exec(line);
      if (!m) continue;
      const tokens = m[1].replace(/#.*$/, '').trim().split(/\s+/);
      const [area, command] = tokens;
      if (!/^[a-z]+$/.test(area ?? '')) continue; // `caddie-admin ...`, `caddie-admin -h`
      count++;
      const entry = COMMAND_TREE[area]?.commands?.[command];
      if (!entry) {
        problems.push(`${file}: unknown command in: ${line}`);
        continue;
      }
      for (const t of tokens.slice(2)) {
        if (!t.startsWith('--')) continue;
        const flag = t.slice(2).replace(/[^a-z-].*$/, '');
        if (!GLOBAL_FLAGS.includes(flag) && !Object.hasOwn(entry.options, flag)) problems.push(`${file}: ${area} ${command} does not take --${flag}: ${line}`);
      }
    }
  }
  assert.ok(count > 25, `only ${count} examples found`);
  assert.deepEqual(problems, []);
});

test('every `node <script>` line in the documents uses flags that the script knows', () => {
  const problems = [];
  let count = 0;
  for (const file of NEW_DOCS) {
    for (const line of commandLines(file)) {
      const m = /(?:^|[\s(])node\s+((?:scripts|worker|tools)\/[A-Za-z0-9_./-]+\.mjs)\s*(.*)$/.exec(line);
      if (!m || m[1] === 'scripts/caddie-admin.mjs') continue;
      const [, script, rest] = m;
      if (!fs.existsSync(path.join(ROOT, script))) {
        problems.push(`${file}: ${script} does not exist`);
        continue;
      }
      count++;
      const source = read(script);
      for (const f of rest.matchAll(/(?:^|\s)(--[a-z][a-z-]*)/g)) {
        if (!source.includes(f[1])) problems.push(`${file}: ${script} has no ${f[1]}: ${line}`);
      }
    }
  }
  assert.ok(count > 15, `only ${count} node examples found`);
  assert.deepEqual(problems, []);
});

test('every gh variable, secret, workflow and run command in the guides names its repository', () => {
  const problems = [];
  let count = 0;
  for (const file of NEW_DOCS) {
    for (const line of commandLines(file)) {
      for (const m of line.matchAll(/\bgh (variable|secret|workflow|run)\b[^|`]*/g)) {
        if (/^gh (workflow|run) (disable|enable)?\s*$/.test(m[0])) continue;
        count++;
        if (!/--repo[ =]/.test(m[0])) problems.push(`${file}: no --repo in: ${line}`);
      }
    }
  }
  assert.ok(count > 15, `only ${count} gh commands found`);
  assert.deepEqual(problems, []);
});

test('every "`SYMBOL` in `path`" citation names a symbol that the file contains', () => {
  const problems = [];
  let count = 0;
  for (const file of NEW_DOCS) {
    for (const m of read(file).matchAll(/`([A-Za-z_][A-Za-z0-9_.]*)`(?: \([^)]*\))? in `((?:scripts|worker|native|web|server|data|config|contracts|tools|test|\.github)\/[^`\s]+)`/g)) {
      const [, symbol, target] = m;
      if (!fs.existsSync(path.join(ROOT, target))) continue; // the path test reports a missing file
      count++;
      if (!read(target).includes(symbol)) problems.push(`${file}: ${target} does not contain ${symbol}`);
    }
  }
  assert.ok(count >= 3, `only ${count} citations found`);
  assert.deepEqual(problems, []);
});

